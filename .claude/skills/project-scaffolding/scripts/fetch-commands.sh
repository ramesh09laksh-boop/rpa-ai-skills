#!/usr/bin/env bash
#
# Fetch the rpa-ai-skills slash commands into a UC project.
#
#   fetch-commands.sh [-r <repo-url>] [-b <ref>] [-d <dest>] [-f] -a <agent> [-a <agent>...]
#
# `npx skills add` installs SKILLS, not commands -- it has no concept of them, so a project
# that has the skills still has no /start. This script is the other half: a blobless, depth-1,
# sparse checkout of the one command folder each agent reads.
#
# The command files in the repo are GENERATED from commands/<name>.md by
# templates/tools/build-commands.ps1 (maintainer-side; not in your project). This script only
# copies the generated result, so there is nothing to build here.
#
# Works with no setup: the canonical repo is the default. Override with -r, or by setting
# RPA_SKILLS_REPO, when you work from a fork or an internal mirror.
# Precedence: -r  >  $RPA_SKILLS_REPO  >  default.

set -euo pipefail

DEFAULT_REPO="https://github.com/ramesh09laksh-boop/rpa-ai-skills"

if [ -n "${RPA_SKILLS_REPO:-}" ]; then
    REPO="$RPA_SKILLS_REPO"
    REPO_SOURCE="\$RPA_SKILLS_REPO"
else
    REPO="$DEFAULT_REPO"
    REPO_SOURCE="default"
fi

REF=""
DEST="."
FORCE=0
AGENTS=()

# Agent ids are the `skills` CLI's own, so one vocabulary covers both halves of the install.
# `copilot` is deliberately absent: the CLI rejects it, and accepting it here would teach the
# wrong id.
VALID_AGENTS="claude-code github-copilot opencode"

# Where each agent reads commands from. Verified against each product's current documentation
# on 2026-11-23. OpenCode's folder is PLURAL; its legacy singular `command/` is still
# discovered but is not what new files should use.
agent_dir() {
    case "$1" in
        claude-code)    echo ".claude/commands" ;;
        github-copilot) echo ".github/prompts" ;;
        opencode)       echo ".opencode/commands" ;;
    esac
}

MARKER="GENERATED by templates/tools/build-commands.ps1"

usage() {
    cat <<EOF
Usage: $(basename "$0") [-r <repo-url>] [-b <ref>] [-d <dest>] [-f] -a <agent> [-a <agent>...]

  -a <agent>     Agent to install for. Repeatable, or '*' for all of them. REQUIRED.
                 Valid: $VALID_AGENTS
  -r <repo-url>  Git URL of rpa-ai-skills. Overrides \$RPA_SKILLS_REPO.
                 Default: $DEFAULT_REPO
  -b <ref>       Branch or tag to fetch. Defaults to the remote's default branch.
                 Pin the same tag you pinned the skills to.
  -d <dest>      Project root to install into. Defaults to the current directory.
  -f             Overwrite a file that is NOT a generated command. Off by default.
  -h             This message.

A generated command is always overwritten -- that is what re-running this for an update means.
A file of the same name that does not carry the generator's marker is left alone unless -f.

Examples:
  $(basename "$0") -a claude-code
  $(basename "$0") -a claude-code -a github-copilot -a opencode
  $(basename "$0") -a '*' -b v0.2.5          # pinned, same ref as the skills
EOF
}

while getopts ':a:r:b:d:fh' opt; do
    case "$opt" in
        a) AGENTS+=("$OPTARG") ;;
        r) REPO="$OPTARG"; REPO_SOURCE="-r" ;;
        b) REF="$OPTARG" ;;
        d) DEST="$OPTARG" ;;
        f) FORCE=1 ;;
        h) usage; exit 0 ;;
        :) echo "error: -$OPTARG requires an argument" >&2; usage >&2; exit 2 ;;
        \?) echo "error: unknown option -$OPTARG" >&2; usage >&2; exit 2 ;;
    esac
done
shift $((OPTIND - 1))

command -v git >/dev/null 2>&1 || { echo "error: git is not on PATH" >&2; exit 1; }

if [ "${#AGENTS[@]}" -eq 0 ]; then
    echo "error: name at least one agent with -a." >&2
    usage >&2
    exit 2
fi

if [ -z "$REPO" ]; then
    echo "error: repository URL is empty ($REPO_SOURCE)." >&2
    echo "       Unset it to fall back to the default, or pass a real URL to -r." >&2
    exit 2
fi

# Expand '*' and reject anything unknown, so a stray argument cannot turn into an arbitrary
# sparse-checkout path.
RESOLVED=()
for requested in "${AGENTS[@]}"; do
    if [ "$requested" = "*" ]; then
        for known in $VALID_AGENTS; do RESOLVED+=("$known"); done
        continue
    fi
    matched=""
    for known in $VALID_AGENTS; do
        [ "$requested" = "$known" ] && matched="$known" && break
    done
    if [ -z "$matched" ]; then
        echo "error: unknown agent '$requested'." >&2
        echo "       Valid: $VALID_AGENTS  (or '*')" >&2
        echo "       These are the \`skills\` CLI's own ids. 'copilot' is not one of them." >&2
        exit 2
    fi
    RESOLVED+=("$matched")
done

# De-duplicate, so -a '*' -a claude-code does not copy twice.
AGENTS=()
for a in "${RESOLVED[@]}"; do
    seen=0
    for b in ${AGENTS[@]+"${AGENTS[@]}"}; do [ "$a" = "$b" ] && seen=1 && break; done
    [ "$seen" -eq 0 ] && AGENTS+=("$a")
done

mkdir -p "$DEST"
DEST_ABS="$(cd "$DEST" && pwd)"

WORK="$(mktemp -d)"
cleanup() { rm -rf "$WORK"; }
trap cleanup EXIT

echo "Fetching from $REPO [$REPO_SOURCE]${REF:+ (ref: $REF)}"

CLONE_ARGS=(--filter=blob:none --sparse --depth 1)
[ -n "$REF" ] && CLONE_ARGS+=(--branch "$REF")

if ! git clone "${CLONE_ARGS[@]}" "$REPO" "$WORK/repo" >/dev/null; then
    echo "" >&2
    echo "error: could not clone $REPO [$REPO_SOURCE]." >&2
    if [ "$REPO_SOURCE" = "default" ]; then
        cat >&2 <<EOF
       GitHub reports "not found" both for a repo that does not exist and for a
       private repo you are not authenticated to. If this one is private, set up
       credentials (gh auth login, SSH key, or a PAT) and retry. If your team works
       from a fork or an internal mirror, point at it instead:

         export RPA_SKILLS_REPO=<your-url>     # once, per developer
         $(basename "$0") -r <your-url> ...    # or per invocation
EOF
    fi
    exit 1
fi

SPARSE_PATHS=()
for a in "${AGENTS[@]}"; do
    SPARSE_PATHS+=("$(agent_dir "$a")")
done
git -C "$WORK/repo" sparse-checkout set "${SPARSE_PATHS[@]}" >/dev/null

COPIED=0
SKIPPED=0

for a in "${AGENTS[@]}"; do
    src_rel="$(agent_dir "$a")"
    src="$WORK/repo/$src_rel"
    if [ ! -d "$src" ]; then
        echo "error: $src_rel not found in $REPO${REF:+ at $REF}." >&2
        echo "       That ref predates the commands. Fetch a newer ref, or omit -b." >&2
        exit 1
    fi

    target="$DEST_ABS/$src_rel"
    mkdir -p "$target"
    echo "  $a -> $src_rel"

    for f in "$src"/*; do
        [ -f "$f" ] || continue
        name="$(basename "$f")"
        if [ -f "$target/$name" ] && [ "$FORCE" -eq 0 ] && ! grep -aq "$MARKER" "$target/$name"; then
            echo "    skipped $name - exists and is not a generated command (-f to overwrite)"
            SKIPPED=$((SKIPPED + 1))
            continue
        fi
        cp "$f" "$target/$name"
        COPIED=$((COPIED + 1))
    done
done

echo ""
# Not ${SKIPPED:+...}: "0" is a non-empty string, so that form reports ", skipped 0".
if [ "$SKIPPED" -gt 0 ]; then
    echo "Copied $COPIED command file(s), skipped $SKIPPED."
else
    echo "Copied $COPIED command file(s)."
fi
cat <<'EOF'

Type /start in the agent to begin, or to pick the build back up. /start <number> jumps to a
stage; /start next resumes.

These files are GENERATED and are overwritten by the next run of this script. Do not hand-edit
them in the project: a change belongs in rpa-ai-skills, where every project gets it.

Re-run this after `npx skills update` -- that command updates skills and knows nothing about
commands, so the two halves do not update together on their own.
EOF
