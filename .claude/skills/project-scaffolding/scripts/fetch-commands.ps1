#Requires -Version 7.0
<#
.SYNOPSIS
    Fetch the rpa-ai-skills slash commands into a UC project. PowerShell twin of
    fetch-commands.sh.

.DESCRIPTION
    `npx skills add` installs SKILLS, not commands — it has no concept of them, so a project
    that has the skills still has no /start. This script is the other half: a blobless,
    depth-1, sparse checkout of the one command folder each agent reads.

    The command files in the repo are generated from its commands/ sources by a maintainer-side
    build script (maintainer provenance — not in your project). This script copies the
    generated result, so there is nothing to build here.

    Works with no setup: the canonical repo is the default. Override with -RepoUrl, or by
    setting $env:RPA_SKILLS_REPO, when you work from a fork or an internal mirror.
    Precedence: -RepoUrl > $env:RPA_SKILLS_REPO > default.

.PARAMETER Agent
    One or more agent ids, or '*' for all of them. Required. These are the `skills` CLI's own
    ids, so one vocabulary covers both halves of the install — 'copilot' is not one of them and
    is rejected here for the same reason the CLI rejects it.

.PARAMETER RepoUrl
    Git URL of rpa-ai-skills. Overrides $env:RPA_SKILLS_REPO.

.PARAMETER Ref
    Branch or tag to fetch. Defaults to the remote's default branch. Pin the same tag you
    pinned the skills to.

.PARAMETER Dest
    Project root to install into. Defaults to the current directory.

.PARAMETER Force
    Overwrite a file that is NOT a generated command. Off by default. A generated command is
    always overwritten — that is what re-running this for an update means.

.PARAMETER OpenCodeLegacyDir
    OpenCode only: install into the legacy singular `.opencode/command/` instead of
    `.opencode/commands/`. Use it if /start does not appear in your OpenCode version's / menu.

    The current OpenCode docs say `commands/` (plural), and that the singular `command/` is
    still discovered but is not what new files should use — so plural is the default. This is a
    flag rather than "install into both" because a version that reads both would then show
    every command twice.

.EXAMPLE
    pwsh -File fetch-commands.ps1 -Agent claude-code

.EXAMPLE
    pwsh -File fetch-commands.ps1 -Agent '*' -Ref v0.2.5

.EXAMPLE
    pwsh -File fetch-commands.ps1 -Agent opencode -OpenCodeLegacyDir
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string[]] $Agent,
    [string] $RepoUrl,
    [string] $Ref,
    [string] $Dest = '.',
    [switch] $Force,
    [switch] $OpenCodeLegacyDir
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$defaultRepo = 'https://github.com/ramesh09laksh-boop/rpa-ai-skills'

if ($RepoUrl) { $repo = $RepoUrl; $repoSource = '-RepoUrl' }
elseif ($env:RPA_SKILLS_REPO) { $repo = $env:RPA_SKILLS_REPO; $repoSource = '$env:RPA_SKILLS_REPO' }
else { $repo = $defaultRepo; $repoSource = 'default' }

if (-not $repo) {
    Write-Error "Repository URL is empty ($repoSource). Unset it to fall back to the default, or pass a real URL to -RepoUrl."
    exit 2
}

# Where each agent reads commands from. Verified against each product's current documentation
# on 2026-11-23. OpenCode's folder is PLURAL; its legacy singular `command/` is still
# discovered but is not what new files should use.
$agentDirs = [ordered]@{
    'claude-code'    = '.claude/commands'
    'github-copilot' = '.github/prompts'
    'opencode'       = '.opencode/commands'
}

$marker = 'GENERATED by templates/tools/build-commands.ps1'

$resolved = [System.Collections.Generic.List[string]]::new()
foreach ($a in $Agent) {
    if ($a -eq '*') {
        foreach ($k in $agentDirs.Keys) { if (-not $resolved.Contains($k)) { $resolved.Add($k) } }
        continue
    }
    if (-not $agentDirs.Contains($a)) {
        Write-Error ("Unknown agent '$a'. Valid: $($agentDirs.Keys -join ', ') (or '*'). " +
            'These are the skills CLI''s own ids; ''copilot'' is not one of them.')
        exit 2
    }
    if (-not $resolved.Contains($a)) { $resolved.Add($a) }
}

if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    Write-Error 'git is not on PATH'
    exit 1
}

if (-not (Test-Path -LiteralPath $Dest)) { New-Item -ItemType Directory -Path $Dest -Force | Out-Null }
$destAbs = (Resolve-Path -LiteralPath $Dest).Path

$work = Join-Path ([System.IO.Path]::GetTempPath()) ('rpa-commands-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
New-Item -ItemType Directory -Path $work -Force | Out-Null

try {
    Write-Host "Fetching from $repo [$repoSource]$(if ($Ref) { " (ref: $Ref)" })"

    $cloneArgs = @('clone', '--filter=blob:none', '--sparse', '--depth', '1')
    if ($Ref) { $cloneArgs += @('--branch', $Ref) }
    $cloneArgs += @($repo, (Join-Path $work 'repo'))

    & git @cloneArgs *>$null
    if ($LASTEXITCODE -ne 0) {
        Write-Host ''
        Write-Host "error: could not clone $repo [$repoSource]." -ForegroundColor Red
        if ($repoSource -eq 'default') {
            Write-Host @'
       GitHub reports "not found" both for a repo that does not exist and for a
       private repo you are not authenticated to. If this one is private, set up
       credentials (gh auth login, SSH key, or a PAT) and retry. If your team works
       from a fork or an internal mirror, point at it instead:

         $env:RPA_SKILLS_REPO = '<your-url>'          # once, per developer
         pwsh -File fetch-commands.ps1 -RepoUrl <your-url> ...
'@
        }
        exit 1
    }

    $repoDir = Join-Path $work 'repo'
    $sparse = @($resolved | ForEach-Object { $agentDirs[$_] })
    & git -C $repoDir sparse-checkout set @sparse *>$null

    $copied = 0
    $skipped = 0

    foreach ($a in $resolved) {
        $rel = $agentDirs[$a]
        $src = Join-Path $repoDir $rel
        if (-not (Test-Path -LiteralPath $src)) {
            Write-Error "$rel not found in $repo$(if ($Ref) { " at $Ref" }). That ref predates the commands - fetch a newer ref, or omit -Ref."
            exit 1
        }

        # The destination is the source path, except for OpenCode with -OpenCodeLegacyDir,
        # where the files are the same and only the folder name differs.
        $dstRel = if ($a -eq 'opencode' -and $OpenCodeLegacyDir) { '.opencode/command' } else { $rel }

        $target = Join-Path $destAbs $dstRel
        if (-not (Test-Path -LiteralPath $target)) { New-Item -ItemType Directory -Path $target -Force | Out-Null }
        Write-Host "  $a -> $dstRel"

        foreach ($f in Get-ChildItem -LiteralPath $src -File) {
            $dstPath = Join-Path $target $f.Name
            if ((Test-Path -LiteralPath $dstPath) -and -not $Force) {
                $existing = [System.IO.File]::ReadAllText($dstPath)
                if ($existing -notmatch [regex]::Escape($marker)) {
                    Write-Host "    skipped $($f.Name) - exists and is not a generated command (-Force to overwrite)"
                    $skipped++
                    continue
                }
            }
            Copy-Item -LiteralPath $f.FullName -Destination $dstPath -Force
            $copied++
        }
    }

    Write-Host ''
    if ($skipped -gt 0) { Write-Host "Copied $copied command file(s), skipped $skipped." }
    else { Write-Host "Copied $copied command file(s)." }

    Write-Host @'

Type /start in the agent to begin, or to pick the build back up. /start <number> jumps to a
stage; /start next resumes.

These files are GENERATED and are overwritten by the next run of this script. Do not hand-edit
them in the project: a change belongs in rpa-ai-skills, where every project gets it.

Re-run this after `npx skills update` -- that command updates skills and knows nothing about
commands, so the two halves do not update together on their own.
'@
}
finally {
    Remove-Item -LiteralPath $work -Recurse -Force -ErrorAction SilentlyContinue
}
